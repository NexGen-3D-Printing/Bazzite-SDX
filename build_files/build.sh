#!/bin/bash

set -ouex pipefail

# Copy the contents of system_files/ of the git repo to /
cp -avf "/ctx/system_files"/. /

# Install dnf config-manager if needed
dnf5 install -y dnf-command(config-manager)

# Download the latest Surface kernel repository configuration
# This always fetches the latest Fedora 45 Surface kernel packages
curl -fsSL https://raw.githubusercontent.com/linux-surface/linux-surface/master/pkg/keys/surface.asc | gpg --dearmor -o /usr/share/keyrings/linux-surface.gpg

cat > /etc/yum.repos.d/linux-surface.repo << 'SURFACE_REPO'
[linux-surface]
name=linux-surface
baseurl=https://pkg.surfacelinux.com/fedora/f44/
enabled=1
skip_if_unavailable=1
gpgkey=file:///usr/share/keyrings/linux-surface.gpg
gpgcheck=1
enabled_metadata=1
type=rpm-md
repo_gpgcheck=0
SURFACE_REPO

# Install Linux Surface kernel packages (always latest available)
dnf5 install -y --enablerepo=linux-surface \
    kernel-surface \
    kernel-surface-default \
    iptsd \
    libwacom-surface \
    libwacom-surface-data \
    surface-control \
    surface-dtx-daemon

# Clean up repository files (optional, for smaller image)
rm -f /usr/share/keyrings/linux-surface.gpg
rm -f /etc/yum.repos.d/linux-surface.repo

# Create a marker file with the kernel version info
mkdir -p /etc/bazzite-sdx
cat > /etc/bazzite-sdx/release-info.toml << EOF
# Bazzite-SDX Release Information
# This file is automatically generated during build

version = "1.0.0"
fedora_version = 44
base_image = "ghcr.io/ublue-os/bazzite:stable"
linux_surface_kernel = "latest-available"

[links]
github = "https://github.com/NexGen-3D-Printing/bazzite-sdx"
youtube = "https://www.youtube.com/@NexGen-3D"
bigcartel = "https://nexgen3d.bigcartel.com/"
printables = "https://www.printables.com/@NexGen3D"
reddit = "https://www.reddit.com/user/NexGen-3D/"
kofi = "https://ko-fi.com/nexgen3d"
EOF
